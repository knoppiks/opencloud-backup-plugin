func TestDescribe_DefaultsAreTheValuesHeld(t *testing.T) {
	s := newSample()
	s.Listener.Tags = []string{"a", "b"}
	got := map[string]Variable{}
	for _, v := range Describe(s) {
		got[v.Name] = v
	}
	for name, want := range map[string]Variable{
		"T_ADDR":    {Section: "Listener", Type: "string", Default: ":8080"},
		"T_PATH":    {Section: "Listener", Type: "string", Default: ""},
		"T_TAGS":    {Section: "Listener", Type: "comma-separated list", Default: "a,b"},
		"T_ENABLE":  {Section: "Tuning", Type: "boolean", Default: "false"},
		"T_WORKERS": {Section: "Tuning", Type: "integer", Default: "2"},
		"T_BACKEND": {Section: "Tuning", Type: "one of `memory`, `disk`", Default: ""},
		"T_TOKEN":   {Section: "Tuning", Type: "secret", Default: "", Secret: true},
	} {
		v := got[name]
		v.Name, v.Doc = "", ""
		if v != want {
			t.Errorf("%s = %+v, want %+v", name, v, want)
		}
	}
}

